// Approved composed entries: the only ones a customer sees.
// An entry is approved by Adrian (scripts/tea-wisdom-compose/entries-cli.mjs)
// and only when every Wisdom claim it uses is approved and at the revision
// the entry was written against. A claim corrected since flags the entry
// instead of publishing it (phase 4).
import fs from 'node:fs/promises';
import path from 'node:path';

export async function readEntries(directory) {
  let names = [];
  try { names = (await fs.readdir(directory)).filter(name => name.endsWith('.json')); } catch (error) { if (error?.code !== 'ENOENT') throw error; }
  const files = [];
  for (const name of names.sort()) files.push({ name, file: JSON.parse(await fs.readFile(path.join(directory, name), 'utf8')) });
  return files;
}

/** Why an entry may not be approved, or [] when it may. `claims` are the public approved claims. */
export function approvalRefusals(file, claims) {
  const byId = new Map(claims.map(claim => [claim.claimId, claim]));
  const refusals = [];
  for (const use of file.claimUses ?? []) {
    const claim = byId.get(use.claimId);
    if (!claim) refusals.push(`${use.claimId} is not an approved public claim yet`);
    else if (use.rev !== null && use.rev !== claim.rev) refusals.push(`${use.claimId} is at rev ${claim.rev}; the entry was written against rev ${use.rev}`);
  }
  return refusals;
}

/** Entries marked approved whose claims still hold. Anything else stays off the shop. */
export async function approvedEntries(directory, claims) {
  const entries = {};
  for (const { file } of await readEntries(directory)) {
    if (file.status !== 'approved') continue;
    if (approvalRefusals(file, claims).length) continue;
    entries[file.record.id] = file.entry;
  }
  return entries;
}

export function renderGeneratedEntries(entries) {
  const lines = Object.entries(entries).sort(([left], [right]) => left.localeCompare(right))
    .map(([id, entry]) => `  ${JSON.stringify(id)}: ${JSON.stringify({ ...entry, missing: [] })},`);
  return `/* This file is generated by scripts/tea-reference-markdown/build-pages.mjs from
 * data/tea-reference/entries/: approved composed entries only, keyed by product id. */
import type { ComposedEntry } from './composedEntry';

export const GENERATED_ENTRIES: Readonly<Record<string, ComposedEntry>> = {${lines.length ? `\n${lines.join('\n')}\n` : ''}};
`;
}
