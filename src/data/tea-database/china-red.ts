/**
 * Chinese red teas — hong cha (红茶).
 *
 * Fully oxidized Camellia sinensis from China only.
 * The Western term "black tea" is used internally as the category;
 * the Chinese tradition calls these "red tea" (hong cha) for the colour
 * of the liquor, reserving "black tea" (hei cha) for post-fermented styles.
 *
 * Coverage spans the Wuyi originals (Lapsang Souchong, Jin Jun Mei),
 * Fujian's three classical Gongfu reds (Tanyang, Zhenghe, Bailin),
 * Anhui Keemun, Yunnan Dianhong, and the modern provincial reds of
 * Sichuan, Guangdong, Hubei, Jiangsu, Guizhou, Hunan, and Hainan.
 */

