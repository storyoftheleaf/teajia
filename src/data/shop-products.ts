import { ShopProduct, ProductCategory } from '../types/shop';

/**
 * Default flags for existing inventory items based on their category.
 * Used to extend InventoryItems with shop-specific fields.
 */
export function getDefaultFlags(category: 'tea' | 'ware'): {
  shopCategory: ProductCategory;
  collection: boolean;
  practice: boolean;
  inquiryOnly: boolean;
  shipsInternational: boolean;
  shipsBali: boolean;
} {
  if (category === 'tea') {
    return {
      shopCategory: 'tea',
      collection: false,
      practice: true,
      inquiryOnly: false,
      shipsBali: true,
      shipsInternational: false,
    };
  }
  // teaware
  return {
    shopCategory: 'teaware',
    collection: false,
    practice: true,
    inquiryOnly: false,
    shipsInternational: true,
    shipsBali: true,
  };
}

